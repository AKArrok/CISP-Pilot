def apply_curated_catalog(points: list[dict]) -> list[dict]:
    """补充缺失概念并给已有概念合并别名，保持结果可重复。"""
    by_key = {(point["domain"], _canonical(point["name"])): point for point in points}
    for domain, concepts in CURATED_CONCEPTS.items():
        for name, aliases in concepts.items():
            key = (domain, _canonical(name))
            point = by_key.get(key)
            if point is None:
                point = {
                    "id": _point_id(domain, name), "domain": domain, "name": name,
                    "parent_name": None, "description": None,
                    "evidence_count": 0, "question_count": 0,
                    "status": "active", "recommended": True,
                    "review": {
                        "version": CATALOG_VERSION, "decision": "accept",
                        "reason": "CISP 十域术语表补充的可诊断概念",
                        "original_name": name,
                    },
                }
                points.append(point)
                by_key[key] = point
            point["aliases"] = sorted(set(point.get("aliases", [])) | set(aliases))
    points.sort(key=lambda point: (point["domain"], point["name"], point["id"]))
    return points
