def apply_manual_review(points: list[dict]) -> list[dict]:
    """给首批候选应用逐条人工结论，原地更新并返回列表。"""
    for point in points:
        if not point.get("recommended"):
            continue
        key = (point["domain"], point["name"])
        rejection_reason = REJECTED.get(key)
        if rejection_reason:
            point["status"] = "rejected"
            decision = "reject"
            reason = rejection_reason
        else:
            point["status"] = "active"
            decision = "accept"
            reason = "名称具体且可形成独立诊断目标"
        if key in RENAMED:
            point["name"] = RENAMED[key]
            reason = "规范名称并补足上下文"
        if key in PARENT_OVERRIDES:
            point["parent_name"] = PARENT_OVERRIDES[key]
            reason = "修正课件标题状态串线造成的父级错误"
        point["review"] = {
            "version": REVIEW_VERSION,
            "decision": decision,
            "reason": reason,
            "original_name": key[1],
        }
    return points
